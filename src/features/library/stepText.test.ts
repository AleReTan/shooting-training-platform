import { test, expect } from 'vitest';
import { presentText, splitSentences } from './stepText';

test('серия с местом: номер и место — в заголовок, действия по «;» — построчно и с маркером', () => {
  expect(
    presentText('Серия 5 · 10→25 м: с метки 10 м — 2 в голову левой; отход на левую палку (25 м) — 2 в голову правой'),
  ).toEqual({
    series: 5,
    title: '10→25 м',
    lines: ['с метки 10 м — 2 в голову левой', 'отход на левую палку (25 м) — 2 в голову правой'],
    listed: true,
  });
});

test('перенос строки после заголовка режет длинные перечисления, которые «;» не делит', () => {
  // CoF 50, серия 4: запятые внутри действий — границы задаёт сам текст
  expect(
    presentText('Серия 4 · метка 10 м, спиной к мишеням: разворот на 180° — 5 в левую\nперезарядка с задержки затвора\n5 в правую'),
  ).toEqual({
    series: 4,
    title: 'метка 10 м, спиной к мишеням',
    lines: ['разворот на 180° — 5 в левую', 'перезарядка с задержки затвора', '5 в правую'],
    listed: true,
  });
});

test('заголовки серий USPSA и короткие подписи («Старт», «Счёт») тоже выносятся', () => {
  expect(presentText('Серия 1 (4,5 с): 6 выстрелов в T1 только с левого плеча')).toMatchObject({
    series: 1,
    title: '(4,5 с)',
  });
  expect(presentText('Серия 2: то же с левой стороны баррикады')).toEqual({
    series: 2,
    title: undefined,
    lines: ['то же с левой стороны баррикады'],
    listed: false,
  });
  expect(presentText('Старт: стрелок в боксе A за баррикадой лицом в сторону мишеней; для карабина — ствол касается метки')).toEqual({
    title: 'Старт',
    lines: ['стрелок в боксе A за баррикадой лицом в сторону мишеней', 'для карабина — ствол касается метки'],
    listed: true,
  });
  expect(presentText('String 1 · 5 m mark: from low ready — 1 round to the head')).toMatchObject({
    series: 1,
    title: '5 m mark',
  });
});

test('границы предложений: «. » перед заглавной делит, инициал, скобка и дробь — нет', () => {
  expect(
    splitSentences('хит-фактор = очки ÷ время. Итог по мишеням: левая 2 + 13; правая 2 + 16. Стоп! Дальше'),
  ).toEqual(['хит-фактор = очки ÷ время.', 'Итог по мишеням: левая 2 + 13; правая 2 + 16.', 'Стоп!', 'Дальше']);
  expect(splitSentences('Нормативы дня: Minuteman 4.0+, Militiaman 2.5–3.9. Ночные: те же')).toEqual([
    'Нормативы дня: Minuteman 4.0+, Militiaman 2.5–3.9.',
    'Ночные: те же',
  ]);
  // инициал «Дж.» не рвётся, конец предложения после фамилии — рвётся
  expect(splitSentences('по Дж. Куперу. Далее')).toEqual(['по Дж. Куперу.', 'Далее']);
  expect(splitSentences('верх на 5,5 дюйма ниже (см. PDF врезку). Дальше')).toEqual(['верх на 5,5 дюйма ниже (см. PDF врезку).', 'Дальше']);
  // строчная после точки — не граница («…м. и 10 м»)
  expect(splitSentences('метки 5 м. и 10 м стоят перед мишенью')).toEqual(['метки 5 м. и 10 м стоят перед мишенью']);
});

test('связный шаг без «;» делится только по предложениям и остаётся без маркеров; цель — без заголовка', () => {
  expect(presentText('Карабин в готовности, 6 патронов в магазине. Дистанция — от 3 до 25 ярдов, начни с 10 м')).toEqual({
    title: undefined,
    lines: ['Карабин в готовности, 6 патронов в магазине.', 'Дистанция — от 3 до 25 ярдов, начни с 10 м'],
    listed: false,
  });
  expect(presentText('Положение №1, субъекты и патроны 1+2: дистанция 5 м').title).toBeUndefined();
  expect(presentText('Старт в 2:00 по сигналу').title).toBeUndefined();
  // импорт с переносами строк — по строкам автора
  expect(presentText('По сигналу таймера поражается гонг.\r\nОружие: патруль\r\nПатрон: в патроннике')).toEqual({
    title: undefined,
    lines: ['По сигналу таймера поражается гонг.', 'Оружие: патруль', 'Патрон: в патроннике'],
    listed: true,
  });
  expect(presentText('Гонг 25 м: выстрел, смена магазина и повторное поражение', { title: false })).toEqual({
    title: undefined,
    lines: ['Гонг 25 м: выстрел, смена магазина и повторное поражение'],
    listed: false,
  });
});
